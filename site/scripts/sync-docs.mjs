// Generates the site's Starlight content from the repository's own Markdown, which stays the source of truth.
//
//   node scripts/sync-docs.mjs          one-off sync (astro.config.mjs also runs it on every dev/build start)
//
// Per page: the first `# H1` becomes the title, relative links become site routes (or GitHub URLs for repository
// files that are not pages), images are copied next to the content, GitHub alerts become Starlight asides and stray
// `<placeholder>` text is escaped. Any relative link that resolves to nothing fails the sync.

import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import GithubSlugger from 'github-slugger';
import { toString } from 'mdast-util-to-string';
import remarkGfm from 'remark-gfm';
import remarkParse from 'remark-parse';
import { unified } from 'unified';
import { visitParents } from 'unist-util-visit-parents';

const SITE_DIR = fileURLToPath(new URL('..', import.meta.url));
export const REPO_DIR = join(SITE_DIR, '..');
export const BASE = '/sortie/';
const GITHUB = 'https://github.com/sortie-launcher/sortie';

const CONTENT_DIR = join(SITE_DIR, 'src/content/docs');
const ASSET_DIR = join(SITE_DIR, 'src/assets/repo'); // optimised copies for inline images
const PUBLIC_REPO_DIR = join(SITE_DIR, 'public/repo'); // full-size originals that inline images link to
const BRAND_DIR = join(SITE_DIR, 'src/assets/brand');

const IMAGE_EXT = /\.(png|jpe?g|gif|webp|avif|svg)$/i;
// Tags GitHub would render as HTML. Anything else in angle brackets (`<name>`, `<issue-id>`) is placeholder text.
const HTML_TAGS = new Set(
  'a abbr b blockquote br code dd del details div dl dt em h1 h2 h3 h4 h5 h6 hr i img ins kbd li ol p picture pre q s samp source span strong sub summary sup table tbody td tfoot th thead tr tt u ul var video'.split(
    ' ',
  ),
);
const ALERTS = {
  NOTE: ['note', 'Note'],
  TIP: ['tip', 'Tip'],
  IMPORTANT: ['note', 'Important'],
  WARNING: ['caution', 'Warning'],
  CAUTION: ['danger', 'Caution'],
};

/** Pages, in repository terms. `slug` is the site route below the base; `order` sorts autogenerated groups. */
function pageList() {
  const pages = [
    { src: 'docs/GETTING_STARTED.md', slug: 'getting-started' },
    { src: 'docs/COCOON_IMPORT.md', slug: 'cocoon-import' },
    { src: 'app/src/main/assets/MANUAL.md', slug: 'manual' },
    { src: 'docs/LAUNCHERS.md', slug: 'reference/launchers' },
    { src: 'docs/formats/README.md', slug: 'reference/formats', label: 'Overview', order: 0 },
    { src: 'docs/RELEASE.md', slug: 'project/release' },
    { src: 'docs/HARDENING.md', slug: 'project/hardening' },
    { src: 'CHANGELOG.md', slug: 'project/changelog' },
    { src: 'docs/SPEC.md', slug: 'project/spec' },
    { src: 'docs/NOW_PLAYING.md', slug: 'project/now-playing' },
    { src: 'docs/screenshots/readme/PROVENANCE.md', slug: 'project/screenshots', provenance: true },
  ];
  // Every format document becomes a page, so new ones appear without touching the site.
  for (const name of readdirSync(join(REPO_DIR, 'docs/formats')).sort()) {
    if (!name.endsWith('.md') || name === 'README.md') continue;
    const stem = name.slice(0, -3);
    pages.push({ src: `docs/formats/${name}`, slug: `reference/formats/${stem.toLowerCase()}`, order: 1 });
  }
  // Each other screenshot set's capture record (docs/screenshots/<set>/PROVENANCE.md) becomes a page too.
  for (const set of screenshotSets()) {
    if (set === 'readme' || !existsSync(join(REPO_DIR, 'docs/screenshots', set, 'PROVENANCE.md'))) continue;
    pages.push({ src: `docs/screenshots/${set}/PROVENANCE.md`, slug: `project/screenshots/${set.toLowerCase()}`, provenance: true });
  }
  return pages;
}

/** Subfolders of docs/screenshots/, one per screenshot set (readme/, cocoon/, …). */
function screenshotSets() {
  const root = join(REPO_DIR, 'docs/screenshots');
  if (!existsSync(root)) return [];
  return readdirSync(root, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();
}

const parser = unified().use(remarkParse).use(remarkGfm);
const parse = (text) => parser.parse(text);

/** Applies non-overlapping [start, end, text] edits to `text`. */
function applyEdits(text, edits) {
  edits.sort((a, b) => b[0] - a[0]);
  let last = Infinity;
  for (const [start, end, replacement] of edits) {
    if (end > last) throw new Error(`overlapping edits at offset ${start}`);
    text = text.slice(0, start) + replacement + text.slice(end);
    last = start;
  }
  return text;
}

const isExternal = (url) => /^[a-z][a-z0-9+.-]*:/i.test(url) || url.startsWith('//');
const toPosix = (p) => p.split(sep).join('/');

class Sync {
  constructor() {
    this.pages = pageList();
    this.bySrc = new Map(this.pages.map((p) => [p.src, p]));
    this.errors = [];
    this.copiedImages = new Set();
  }

  error(src, node, message) {
    const line = node?.position?.start.line;
    this.errors.push(`${src}${line ? `:${line}` : ''}: ${message}`);
  }

  /**
   * Resolves a relative URL written in repository file `src`.
   * Returns { url } for a site page, a public image or GitHub, or null when the target does not exist.
   */
  resolve(src, rawUrl, { image = false, mdFile } = {}) {
    if (isExternal(rawUrl) || rawUrl.startsWith('#') || rawUrl === '') return { url: rawUrl };
    const hashAt = rawUrl.indexOf('#');
    const hash = hashAt >= 0 ? rawUrl.slice(hashAt) : '';
    let path = (hashAt >= 0 ? rawUrl.slice(0, hashAt) : rawUrl).replace(/\?.*$/, '');
    try {
      path = decodeURIComponent(path);
    } catch {
      /* keep as written */
    }
    const trailingSlash = path.endsWith('/');
    const repoPath = path.startsWith('/')
      ? posix.normalize(path.slice(1))
      : posix.normalize(posix.join(posix.dirname(src), path));
    if (repoPath.startsWith('..')) return null;
    const cleanPath = repoPath.replace(/\/$/, '');
    const abs = join(REPO_DIR, cleanPath);
    if (!existsSync(abs)) return null;
    const isDir = statSync(abs).isDirectory();
    const page = this.bySrc.get(cleanPath) ?? (isDir ? this.bySrc.get(posix.join(cleanPath, 'README.md')) : undefined);
    if (page) return { url: `${BASE}${page.slug}/${hash}` };
    if (!isDir && IMAGE_EXT.test(cleanPath)) {
      this.copyImage(cleanPath);
      if (image) return { url: toPosix(relative(dirname(mdFile), join(ASSET_DIR, cleanPath))), full: this.publicUrl(cleanPath) };
      return { url: this.publicUrl(cleanPath) };
    }
    const kind = isDir || trailingSlash ? 'tree' : 'blob';
    return { url: `${GITHUB}/${kind}/main/${cleanPath}${hash}` };
  }

  publicUrl(repoPath) {
    return `${BASE}repo/${repoPath.split('/').map(encodeURIComponent).join('/')}`;
  }

  copyImage(repoPath) {
    if (this.copiedImages.has(repoPath)) return;
    this.copiedImages.add(repoPath);
    for (const root of [ASSET_DIR, PUBLIC_REPO_DIR]) {
      const dest = join(root, repoPath);
      mkdirSync(dirname(dest), { recursive: true });
      cpSync(join(REPO_DIR, repoPath), dest);
    }
  }

  /** Pass 1: links, images, definitions and inline HTML. */
  rewriteLinks(page, text, mdFile) {
    const edits = [];
    const tree = parse(text);
    visitParents(tree, (node, ancestors) => {
      const start = node.position?.start.offset;
      const end = node.position?.end.offset;
      if (node.type === 'link' || node.type === 'image' || node.type === 'definition') {
        const slice = text.slice(start, end);
        const target = this.resolve(page.src, node.url, { image: node.type === 'image', mdFile });
        if (!target) {
          this.error(page.src, node, `broken link ${JSON.stringify(node.url)}`);
          return 'skip';
        }
        if (target.url === node.url && !target.full) return node.type === 'link' ? undefined : 'skip';
        const dest = findDestination(slice, node.type);
        if (!dest) {
          this.error(page.src, node, `cannot locate the destination of ${JSON.stringify(node.url)} in the source`);
          return 'skip';
        }
        let replacement = slice.slice(0, dest.start) + target.url + slice.slice(dest.end);
        // GitHub opens a picture full-size when clicked; keep that for images that are not already links.
        const parent = ancestors.at(-1);
        if (node.type === 'image' && target.full && parent?.type !== 'link' && parent?.type !== 'linkReference') {
          replacement = `[${replacement}](${target.full})`;
        }
        if (node.type === 'link') {
          // Rewrite only the destination; children (e.g. a linked image) are handled on their own.
          edits.push([start + dest.start, start + dest.end, target.url]);
          return undefined;
        }
        edits.push([start, end, replacement]);
        return 'skip';
      }
      if (node.type === 'html') {
        const value = this.rewriteHtml(page, node, node.value);
        if (value !== node.value) edits.push([start, end, value]);
      }
      return undefined;
    });
    return applyEdits(text, edits);
  }

  rewriteHtml(page, node, html) {
    if (/^<!--/.test(html.trim())) return html;
    return html.replace(/<(\/?)([A-Za-z][\w-]*)([^<>]*)>/g, (whole, slash, tag, attrs) => {
      if (!HTML_TAGS.has(tag.toLowerCase())) return `&lt;${slash}${tag}${attrs}&gt;`;
      const newAttrs = attrs.replace(/\b(src|href)=("([^"]*)"|'([^']*)')/g, (m, name, _q, dq, sq) => {
        const url = dq ?? sq;
        const target = this.resolve(page.src, url);
        if (!target) {
          this.error(page.src, node, `broken ${name} ${JSON.stringify(url)}`);
          return m;
        }
        return `${name}="${target.url}"`;
      });
      return `<${slash}${tag}${newAttrs}>`;
    });
  }

  /** Pass 2: GitHub alerts to asides, and the H1 to the title. */
  convertStructure(page, text) {
    const edits = [];
    const tree = parse(text);
    let title;
    visitParents(tree, (node) => {
      if (!title && node.type === 'heading' && node.depth === 1) {
        title = toString(node).trim();
        let end = node.position.end.offset;
        while (text[end] === '\n') end++;
        edits.push([node.position.start.offset, end, '']);
        return 'skip';
      }
      if (node.type === 'blockquote') {
        const first = node.children[0];
        const firstText = first?.type === 'paragraph' ? first.children[0] : undefined;
        const match = firstText?.type === 'text' && /^\[!(NOTE|TIP|IMPORTANT|WARNING|CAUTION)\][ \t]*(\n|$)/.exec(firstText.value);
        if (!match) return undefined;
        const [kind, label] = ALERTS[match[1]];
        const { start, end } = node.position;
        const indent = ' '.repeat(start.column - 1);
        const lines = text
          .slice(start.offset, end.offset)
          .split('\n')
          .map((line) => line.replace(/^[ \t]*>[ \t]?/, ''));
        lines[0] = lines[0].replace(/^\[!\w+\][ \t]*/, '');
        if (lines[0] === '') lines.shift();
        const body = lines.map((line, i) => (line === '' ? '' : `${indent}${line}`)).join('\n');
        edits.push([start.offset, end.offset, `:::${kind}[${label}]\n${body}\n${indent}:::`]);
        return 'skip';
      }
      return undefined;
    });
    if (!title) this.error(page.src, null, 'no "# " title heading');
    return { title, body: applyEdits(text, edits).replace(/^\n+/, '') };
  }

  /** Every `##`… heading slug, as GitHub and Astro both compute it. */
  headingSlugs(text) {
    const slugger = new GithubSlugger();
    const out = [];
    visitParents(parse(text), 'heading', (node) => {
      out.push({ depth: node.depth, text: toString(node), slug: slugger.slug(toString(node)) });
    });
    return out;
  }

  description(body) {
    const tree = parse(body);
    const para = tree.children.find((n) => n.type === 'paragraph');
    if (!para) return undefined;
    const text = toString(para).replace(/\s+/g, ' ').trim();
    return text.length > 200 ? `${text.slice(0, 197).replace(/\s+\S*$/, '')}…` : text;
  }

  page(page) {
    // A folder's README becomes that folder's index page, so autogenerated sidebar groups include it.
    const mdFile = join(CONTENT_DIR, page.src.endsWith('/README.md') ? `${page.slug}/index.md` : `${page.slug}.md`);
    const source = readFileSync(join(REPO_DIR, page.src), 'utf8').replace(/\r\n?/g, '\n');
    page.headings = this.headingSlugs(source);
    const linked = this.rewriteLinks(page, source, mdFile);
    const { title, body } = this.convertStructure(page, linked);
    if (!title) return;
    page.title = title;
    const front = {
      title,
      description: this.description(body),
      editUrl: `${GITHUB}/edit/main/${page.src}`,
    };
    const sidebar = {};
    if (page.label) sidebar.label = page.label;
    if (page.order !== undefined) sidebar.order = page.order;
    const yaml = [
      '---',
      ...Object.entries(front)
        .filter(([, v]) => v !== undefined)
        .map(([k, v]) => `${k}: ${JSON.stringify(v)}`),
      ...(Object.keys(sidebar).length
        ? ['sidebar:', ...Object.entries(sidebar).map(([k, v]) => `  ${k}: ${JSON.stringify(v)}`)]
        : []),
      '---',
      `<!-- Generated from ${page.src} by site/scripts/sync-docs.mjs. Edit that file, not this one. -->`,
      '',
    ].join('\n');
    mkdirSync(dirname(mdFile), { recursive: true });
    writeFileSync(mdFile, `${yaml}\n${body}`);
  }

  async run() {
    for (const dir of [CONTENT_DIR, ASSET_DIR, PUBLIC_REPO_DIR, BRAND_DIR]) rmSync(dir, { recursive: true, force: true });
    mkdirSync(CONTENT_DIR, { recursive: true });
    for (const page of this.pages) this.page(page);

    // Landing-page and theme assets.
    for (const set of screenshotSets()) {
      for (const image of readdirSync(join(REPO_DIR, 'docs/screenshots', set))) {
        if (IMAGE_EXT.test(image)) this.copyImage(`docs/screenshots/${set}/${image}`);
      }
    }
    mkdirSync(BRAND_DIR, { recursive: true });
    for (const name of ['mark.svg', 'logo.svg', 'icon.svg', 'social-preview.png']) {
      cpSync(join(REPO_DIR, 'branding', name), join(BRAND_DIR, name));
    }
    cpSync(join(REPO_DIR, 'branding/icon.svg'), join(SITE_DIR, 'public/favicon.svg'));
    cpSync(join(REPO_DIR, 'branding/social-preview.png'), join(SITE_DIR, 'public/social-preview.png'));

    if (this.errors.length) {
      throw new Error(`sync-docs: ${this.errors.length} problem(s) in the repository docs:\n  ${this.errors.join('\n  ')}`);
    }
    return {
      pages: this.pages.map(({ src, slug, title, headings, provenance }) => ({ src, slug, title, headings, provenance })),
    };
  }
}

/** Locates the destination inside a link/image/definition's source, as offsets relative to `slice`. */
function findDestination(slice, type) {
  let at;
  if (type === 'definition') {
    const colon = slice.indexOf(']:');
    if (colon < 0) return null;
    at = colon + 2;
    while (/\s/.test(slice[at])) at++;
  } else {
    const open = slice.lastIndexOf('](');
    if (open < 0) return null; // reference-style link: its definition is rewritten instead
    at = open + 2;
    while (slice[at] === ' ' || slice[at] === '\t' || slice[at] === '\n') at++;
  }
  if (slice[at] === '<') {
    const close = slice.indexOf('>', at);
    return close < 0 ? null : { start: at, end: close + 1 };
  }
  let end = at;
  let depth = 0;
  while (end < slice.length && !/\s/.test(slice[end])) {
    if (slice[end] === '(') depth++;
    else if (slice[end] === ')') {
      if (depth === 0) break;
      depth--;
    }
    end++;
  }
  return { start: at, end };
}

export async function syncDocs() {
  return new Sync().run();
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    const { pages } = await syncDocs();
    console.log(`sync-docs: ${pages.length} pages generated`);
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}
